    @staticmethod
    def _normalize_model_id(model_id: Any) -> str:
        normalized = str(model_id or "").strip()
        if normalized.startswith("claude-"):
            return f"gemini-{normalized}"
        return normalized

    @classmethod
    def _quota_models_from_payload(cls, payload: dict[str, Any]) -> dict[str, dict[str, Any]] | None:
        raw_models = payload.get("models")
        if not isinstance(raw_models, dict):
            return None

        models: dict[str, dict[str, Any]] = {}
        supported_models = set(cls._supported_models())
        for raw_model_id, model_data in raw_models.items():
            raw_model = str(raw_model_id or "").strip()
            model_id = cls._normalize_model_id(raw_model)
            if not model_id:
                continue
            if model_id not in supported_models and not raw_model.startswith("claude-"):
                continue
            if not isinstance(model_data, dict):
                model_data = {}
            quota_info = model_data.get("quotaInfo")
            quota = quota_info if isinstance(quota_info, dict) else {}
            try:
                remaining = float(
                    quota.get("remainingFraction")
                    if quota.get("remainingFraction") is not None
                    else quota.get("remaining", 0.0)
                )
            except (TypeError, ValueError):
                remaining = 0.0
            models[model_id] = {
                "remaining": max(0.0, min(1.0, remaining)),
                "resetTime": quota.get("resetTime"),
                "resetTimeRaw": quota.get("resetTime"),
            }
        return models

    @classmethod
    def _model_ids_from_payload(cls, payload: dict[str, Any]) -> list[str] | None:
        raw_models = payload.get("models")
        if not isinstance(raw_models, dict):
            return None

        model_ids: list[str] = []
        supported_models = set(cls._supported_models())
        for raw_model_id in raw_models:
            raw_model = str(raw_model_id or "").strip()
            model_id = cls._normalize_model_id(raw_model)
            if model_id and (model_id in supported_models or raw_model.startswith("claude-")):
                model_ids.append(model_id)
        return sorted(dict.fromkeys(model_ids))

    @staticmethod
    def _capacity_signal_from_payload(payload: dict[str, Any]) -> CapacitySignal | None:
        models = AntigravityOauthPlugin._quota_models_from_payload(payload)
        if not models:
            return None
        score = max(float(model_quota.get("remaining") or 0.0) for model_quota in models.values())
        return CapacitySignal(
            has_capacity_signal=True,
            capacity_score=score,
            quota_available=score > 0.0,
            capacity_kind="remaining_ratio",
            reason=f"antigravity_models={len(models)}",
        )

    @staticmethod
    def _extract_project_id(payload: dict[str, Any]) -> str:
        project = payload.get("cloudaicompanionProject")
        if isinstance(project, str):
            return project
        if isinstance(project, dict):
            return str(project.get("id") or project.get("name") or "")
        return ""

    async def _discover_project_id(self, runtime_credential: dict[str, Any]) -> str:
        initial_project_id = ""
        metadata = {
            "ideType": "IDE_UNSPECIFIED",
            "platform": "PLATFORM_UNSPECIFIED",
            "pluginType": "GEMINI",
            "duetProject": initial_project_id,
        }
        try:
            load_response = await self._antigravity_post(
                runtime_credential,
                "loadCodeAssist",
                {
                    "cloudaicompanionProject": initial_project_id,
                    "metadata": metadata,
                },
            )
            if load_response is None:
                return _generate_project_id()
            load_response.raise_for_status()
            load_payload = load_response.json()
            if not isinstance(load_payload, dict):
                return _generate_project_id()

            project_id = self._extract_project_id(load_payload)
            if project_id:
                return project_id

            allowed_tiers = load_payload.get("allowedTiers")
            default_tier = None
            if isinstance(allowed_tiers, list):
                default_tier = next(
                    (tier for tier in allowed_tiers if isinstance(tier, dict) and tier.get("isDefault")),
                    None,
                )
            tier_id = str((default_tier or {}).get("id") or "free-tier")
            onboard_body = {
                "tierId": tier_id,
                "cloudaicompanionProject": initial_project_id,
                "metadata": metadata,
            }

            for _ in range(30):
                onboard_response = await self._antigravity_post(
                    runtime_credential,
                    "onboardUser",
                    onboard_body,
                )
                if onboard_response is None:
                    return _generate_project_id()
                onboard_response.raise_for_status()
                onboard_payload = onboard_response.json()
                if not isinstance(onboard_payload, dict):
                    return _generate_project_id()
                if onboard_payload.get("done"):
                    response_payload = onboard_payload.get("response")
                    if isinstance(response_payload, dict):
                        project = response_payload.get("cloudaicompanionProject")
                        if isinstance(project, dict):
                            project_id = str(project.get("id") or project.get("name") or "")
                        else:
                            project_id = str(project or "")
                    if project_id:
                        return project_id
                await asyncio.sleep(2)
        except Exception:
            return _generate_project_id()

        return _generate_project_id()

    def _normalize_access_credential(self, credential: dict[str, Any]) -> dict[str, Any]:
        normalized = dict(self._normalize_credential(credential))
        if not normalized.get("access_token"):
            raise ValueError("credential.access_token is required")
        return normalized

    def _normalize_project_runtime_credential(self, credential: dict[str, Any]) -> dict[str, Any] | None:
        normalized = self._normalize_access_credential(credential)
        if not str(normalized.get("project_id") or "").strip():
            return None
        return normalized

    def _is_oauth_credential_fresh(self, credential: dict[str, Any]) -> bool:
        normalized = self._normalize_credential(credential)
        if not normalized.get("refresh_token"):
            return bool(normalized.get("access_token"))
        if not normalized.get("access_token"):
            return False
        return not self._is_near_expiry(normalized)

    async def _refresh_oauth_credential(self, credential: dict[str, Any]) -> dict[str, Any] | None:
        try:
            normalized = self._normalize_credential(credential)
            refreshed = await self._refresh_credential(normalized)
        except Exception:
            return None
        return self._persist_credential(refreshed)

    async def _build_runtime_credential(self, credential: dict[str, Any]) -> dict[str, Any]:
        project_id = str(credential.get("project_id") or "").strip()
        normalized = dict(self._normalize_credential(credential))
        runtime_credential = dict(normalized)
        runtime_credential["project_id"] = project_id or await self._discover_project_id(runtime_credential)
        return runtime_credential

    @staticmethod
    def _fallback_models() -> list[str]:
        return AntigravityOauthPlugin._supported_models()

    async def prepare_credential(self, credential: dict[str, Any]) -> CredentialPreparationResult:
        persisted_credential = self._persist_credential(self._normalize_credential(credential))
        return CredentialPreparationResult(
            credential=persisted_credential,
            changed=persisted_credential != credential,
        )

    async def fetch_models(self, credential: dict[str, Any]) -> list[str]:
        try:
            runtime_credential = self._normalize_access_credential(credential)
        except Exception:
            return self._fallback_models()
        response = await self._fetch_available_models(runtime_credential)
        if response is None or not response.is_success:
            return self._fallback_models()

        try:
            payload = response.json()
        except Exception:
            return self._fallback_models()
        if not isinstance(payload, dict):
            return self._fallback_models()

        models = self._model_ids_from_payload(payload)
        if models is None:
            return self._fallback_models()
        return models

    async def is_credential_available(self, credential: dict[str, Any]) -> bool:
        try:
            runtime_credential = self._normalize_access_credential(credential)
        except Exception:
            return False
        response = await self._fetch_available_models(runtime_credential)
        if response is None or not response.is_success:
            return False
        try:
            payload = response.json()
        except Exception:
            return False
        return isinstance(payload, dict) and self._model_ids_from_payload(payload) is not None

    async def get_capacity_signal(self, credential: dict[str, Any]) -> CapacitySignal | None:
        try:
            runtime_credential = self._normalize_project_runtime_credential(credential)
        except Exception:
            return None
        if runtime_credential is None:
            return None
        response = await self._fetch_models_with_quotas(runtime_credential)
        if response is None or not response.is_success:
            return None

        try:
            payload = response.json()
        except Exception:
            return None
        if not isinstance(payload, dict):
            return None
        return self._capacity_signal_from_payload(payload)

    async def explain_credential(self, credential: dict[str, Any]) -> dict:
        try:
            normalized = self._normalize_credential(credential)
            status = "ok"
        except Exception:
            normalized = dict(credential)
            status = "invalid_credential"

        expiry_ms = self._expiry_date_ms(normalized)
        expired = None
        if expiry_ms is not None:
            expired = datetime.fromtimestamp(expiry_ms / 1000, tz=timezone.utc).isoformat()

        return {
            "provider": self.name,
            "status": status,
            "model_source": self.model_source,
            "auth_type": self.auth_type,
            "credential_hint": self._mask_token(normalized.get("access_token")),
            "email": normalized.get("email", ""),
            "type": normalized.get("type", ""),
            "expired": expired,
            "has_refresh_token": bool(normalized.get("refresh_token")),
            "has_project_id": bool(str(normalized.get("project_id") or "").strip()),
        }
