    async def _fetch_models_with_quotas(self, runtime_credential: dict[str, Any]) -> httpx.Response | None:
        return await self._antigravity_post(
            runtime_credential,
            "fetchAvailableModels",
            {"project": runtime_credential["project_id"]},
        )

